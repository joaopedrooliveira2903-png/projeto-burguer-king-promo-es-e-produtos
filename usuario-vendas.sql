create table if not exists public.vendas (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references auth.users(id) on delete cascade,
    total numeric(10,2) not null check (total >= 0),
    status text not null default 'PENDENTE' check (status in ('PENDENTE', 'CONFIRMADA', 'CANCELADA', 'CONCLUIDA')),
    criado_em timestamptz not null default now()
);

create table if not exists public.itens_venda (
    id bigint generated by default as identity primary key,
    venda_id bigint not null references public.vendas(id) on delete cascade,
    produto_id bigint not null references public.produtos_servicos(id),
    quantidade integer not null check (quantidade > 0),
    preco_unitario numeric(10,2) not null check (preco_unitario >= 0)
);

alter table public.vendas enable row level security;
alter table public.itens_venda enable row level security;

drop policy if exists "cliente cria suas vendas" on public.vendas;
drop policy if exists "cliente vê suas vendas" on public.vendas;
drop policy if exists "cliente cria itens da própria venda" on public.itens_venda;
drop policy if exists "cliente vê itens da própria venda" on public.itens_venda;
create policy "cliente cria suas vendas" on public.vendas for insert to authenticated with check (auth.uid() = usuario_id);
create policy "cliente vê suas vendas" on public.vendas for select to authenticated using (auth.uid() = usuario_id);
create policy "cliente cria itens da própria venda" on public.itens_venda for insert to authenticated with check (exists (select 1 from public.vendas where vendas.id = venda_id and vendas.usuario_id = auth.uid()));
create policy "cliente vê itens da própria venda" on public.itens_venda for select to authenticated using (exists (select 1 from public.vendas where vendas.id = venda_id and vendas.usuario_id = auth.uid()));

-- Regras restritivas garantem isolamento por usuário mesmo se houver políticas antigas permissivas.
drop policy if exists "somente dono consulta vendas" on public.vendas;
drop policy if exists "somente dono cria vendas" on public.vendas;
drop policy if exists "somente dono remove venda pendente" on public.vendas;
drop policy if exists "somente dono remove venda pendente restritivo" on public.vendas;
drop policy if exists "somente dono consulta itens da venda" on public.itens_venda;
drop policy if exists "somente dono cria itens da venda" on public.itens_venda;
create policy "somente dono consulta vendas" on public.vendas
    as restrictive for select to authenticated
    using (auth.uid() = usuario_id);
create policy "somente dono cria vendas" on public.vendas
    as restrictive for insert to authenticated
    with check (auth.uid() = usuario_id);
create policy "somente dono remove venda pendente" on public.vendas
    for delete to authenticated
    using (auth.uid() = usuario_id and status = 'PENDENTE');
create policy "somente dono remove venda pendente restritivo" on public.vendas
    as restrictive for delete to authenticated
    using (auth.uid() = usuario_id and status = 'PENDENTE');
create policy "somente dono consulta itens da venda" on public.itens_venda
    as restrictive for select to authenticated
    using (exists (
        select 1 from public.vendas
        where vendas.id = itens_venda.venda_id
          and vendas.usuario_id = auth.uid()
    ));
create policy "somente dono cria itens da venda" on public.itens_venda
    as restrictive for insert to authenticated
    with check (exists (
        select 1 from public.vendas
        where vendas.id = itens_venda.venda_id
          and vendas.usuario_id = auth.uid()
    ));

-- Perfil público do usuário. Se a tabela já existir, mantenha sua estrutura atual.
create or replace function public.criar_perfil_usuario()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
    insert into public.usuarios (id, email, nome, tipo_usuario)
    values (new.id, new.email, coalesce(new.raw_user_meta_data->>'nome', 'Cliente'), 'USER')
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists criar_perfil_usuario on auth.users;
create trigger criar_perfil_usuario
after insert on auth.users
for each row execute procedure public.criar_perfil_usuario();

-- Também cria perfis para contas cadastradas antes da instalação do trigger.
-- Perfis existentes, incluindo o tipo de usuário, não são alterados.
insert into public.usuarios (id, email, nome, tipo_usuario)
select
    users.id,
    users.email,
    coalesce(users.raw_user_meta_data->>'nome', 'Cliente'),
    'USER'
from auth.users as users
on conflict (id) do nothing;

